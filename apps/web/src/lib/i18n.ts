export const dictionaries: Record<Locale, Dict> = { en, ru, uz };

export type Params = Record<string, string | number>;

export function translate(locale: Locale, key: DictKey, params?: Params): string {
  const raw = dictionaries[locale][key] ?? en[key];
  return params ? raw.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`)) : raw;
}

const current = () => useMissionStore.getState().locale;

/** Non-hook translators for modules that run outside React (alerts, voice, log export). */
export const tr = (key: DictKey, params?: Params) => translate(current(), key, params);
export const statusWord = (s: Status, locale: Locale = current()) => translate(locale, `st.${s}` as DictKey);
export const metricName = (metric: string, locale: Locale = current()) =>
  translate(locale, `name.${metric}` as DictKey) === `name.${metric}` ? metric : translate(locale, `name.${metric}` as DictKey);

const UNIT_KEY: Record<string, DictKey> = {
  '%': 'unit.pct', bpm: 'unit.bpm', mmHg: 'unit.mmHg', '/min': 'unit.perMin', ms: 'unit.ms', '°C': 'unit.celsius',
  'µSv/h': 'unit.uSvh', mSv: 'unit.mSv', idx: 'unit.idx', 'µV': 'unit.uV',
};
export const spokenUnit = (unit: string, locale: Locale = current()) =>
  UNIT_KEY[unit] ? translate(locale, UNIT_KEY[unit]) : unit;

export function useT() {
  const locale = useMissionStore((s) => s.locale);
  return (key: DictKey, params?: Params) => translate(locale, key, params);
}
